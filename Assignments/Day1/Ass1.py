#int method
a = 10.5
print(int(a)) #float to int
print(type(int(a)))

b = "10"
print(int(b)) #string to int
print(type(int(b)))

#float method
c = 10
print(float(c)) #int to float
print(type(float(c)))
d="10.5"
print(float(d)) #string to float
print(type(float(d)))

#complex method
e = 10
print(complex(e)) #int to complex
print(type(complex(e)))

#bool method
f = 0
print(bool(f)) #int to bool
print(type(bool(f)))
g = 10
print(bool(g)) #int to bool
print(type(bool(g)))


#str method
h = 10
print(str(h)) #int to str
print(type(str(h)))
i = 10.5
print(str(i)) #float to str
print(type(str(i)))